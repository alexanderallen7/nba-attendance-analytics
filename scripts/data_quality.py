"""Generate DATA_QUALITY.md from data/processed/attendance.db.

Run after scripts/build_db.py:
    python scripts/data_quality.py
"""

from __future__ import annotations

import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "data" / "processed" / "attendance.db"
OUT = ROOT / "DATA_QUALITY.md"


def rows(con, sql):
    return con.execute(sql).fetchall()


def main() -> None:
    con = sqlite3.connect(DB)

    season_tbl = rows(con, """
        SELECT season, COUNT(*),
               SUM(attendance IS NULL),
               SUM(excluded_flag),
               SUM(CASE WHEN excluded_flag=0 AND attendance IS NULL THEN 1 ELSE 0 END)
        FROM game_features GROUP BY season ORDER BY season""")

    total, usable = rows(con, """
        SELECT COUNT(*),
               SUM(CASE WHEN excluded_flag=0 AND fill_rate IS NOT NULL THEN 1 ELSE 0 END)
        FROM game_features""")[0]

    over_cap = rows(con, """
        SELECT COUNT(*), ROUND(MAX(fill_rate_raw), 3)
        FROM game_features WHERE excluded_flag=0 AND fill_rate_raw > 1""")[0]

    excl = rows(con, """
        SELECT excluded_reason, COUNT(*) FROM game_features
        WHERE excluded_flag=1 GROUP BY 1 ORDER BY 2 DESC""")

    unmatched = rows(con, """
        SELECT COUNT(*) FROM game_features
        WHERE capacity IS NULL AND excluded_reason IS NULL""")[0][0]

    low_att = rows(con, """
        SELECT game_date, home_team, away_team, attendance
        FROM game_features WHERE excluded_flag=0 AND attendance < 6000
        ORDER BY game_date""")

    low_att_restriction = rows(con, """
        SELECT game_date, home_team, attendance FROM game_features
        WHERE excluded_flag=0 AND home_team='TOR'
          AND season_start_year=2021 AND attendance < 12000
        ORDER BY game_date""")

    opener_nulls = rows(con, """
        SELECT COUNT(*) FROM game_features
        WHERE home_win_pct_entering IS NULL OR opp_win_pct_entering IS NULL""")[0][0]

    arena_changes = rows(con, """
        SELECT team, COUNT(*) FROM arena_capacity GROUP BY team HAVING COUNT(*) > 1""")

    lines = []
    w = lines.append
    w("# Data quality report")
    w("")
    w("Generated by `scripts/data_quality.py` from `data/processed/attendance.db`.")
    w("")
    w("## Row counts")
    w("")
    w(f"- Total regular-season games, 2013-14 through 2022-23: **{total:,}**")
    w(f"- Usable for analysis (not excluded, attendance present): **{usable:,}**")
    w("")
    w("| Season | Games | Missing attendance | Excluded | Missing att. among non-excluded |")
    w("|---|---|---|---|---|")
    for s, n, miss, exc, missne in season_tbl:
        w(f"| {s} | {n:,} | {miss} | {exc} | {missne} |")
    w("")
    w("The source database has no attendance value for roughly 8-10% of games")
    w("in every season; this is a gap in the source's `game_info` table, not")
    w("concentrated in any team or month. Those rows are kept in the extract")
    w("with a null fill rate and drop out of the regression and fill-rate views.")
    w("")
    w("The source is also missing the 2012-13 season entirely, which is one")
    w("reason the window starts at 2013-14.")
    w("")
    w("## Excluded games")
    w("")
    w("| Reason | Games |")
    w("|---|---|")
    for r, n in excl:
        w(f"| {r} | {n:,} |")
    w("")
    w("- `covid_bubble`: 2019-20 games on/after 2020-07-30 (Orlando, no fans).")
    w("- `covid_limited_capacity`: the entire 2020-21 season (closed or reduced arenas).")
    w("- `international_game`: London / Mexico City / Paris regular-season games,")
    w("  from the curated list in `data/neutral_site_games.csv` (each row cited).")
    w("- `alternate_venue`: San Antonio's 2023-01-13 game at the Alamodome")
    w("  (attendance 68,323 - a record crowd in a football stadium, not AT&T Center).")
    w("")
    w("## Attendance above capacity (cap rule)")
    w("")
    w(f"- Non-excluded games with reported attendance above listed capacity: **{over_cap[0]:,}**")
    w(f"  (max ratio {over_cap[1]}).")
    w("")
    w("Teams routinely report attendance above listed seating capacity (standing")
    w("room, suites, temporary seating). Rule chosen and applied everywhere:")
    w("`fill_rate` = attendance / capacity **capped at 1.0**; the uncapped value is")
    w("kept in `fill_rate_raw`; `sellout_flag` = attendance >= capacity.")
    w("")
    w("## Arena and capacity changes handled")
    w("")
    w("Teams with more than one capacity era in `data/arena_capacity.csv`")
    w("(arena moves: DET 2017, GSW 2019, MIL 2018, SAC 2016; renovations/expansions:")
    w("ATL, BOS, CLE, PHX):")
    w("")
    for team, n in arena_changes:
        w(f"- {team}: {n} eras")
    w("")
    w(f"- Non-excluded games with no capacity match: **{unmatched}** (build fails tests if > 0).")
    w("")
    w("## Known residual issues")
    w("")
    if low_att_restriction:
        w("Two Toronto home games in December 2021 were played under Ontario's")
        w("50% COVID capacity restriction and are kept (not excluded), since the")
        w("league-wide 2021-22 season was otherwise at full capacity:")
        w("")
        for d, t, a in low_att_restriction:
            w(f"- {d} {t}: attendance {a:,}")
        w("")
    extra_low = [r for r in low_att]
    w(f"- Other non-excluded games with attendance below 6,000: **{len(extra_low)}**.")
    w("- Attendance is team-reported (tickets distributed, not turnstile count);")
    w("  several arenas report identical sellout figures for long stretches.")
    w("- Capacity for stable arenas is the current figure from Wikipedia's arena")
    w("  list; minor mid-era reconfigurations below ~500 seats are not modeled.")
    w("")
    w("## Leakage guard")
    w("")
    w(f"- Rows where a team was playing its first game of the season carry a null")
    w(f"  entering win percentage rather than a leaked value: **{opener_nulls}** rows affected.")
    w("- `tests/test_no_leakage.py` recomputes every entering record independently")
    w("  and fails if any entering value includes the current game or later games.")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    con.close()


if __name__ == "__main__":
    main()
